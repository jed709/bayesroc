    }

  }

  if (family_name == "bivariate_cumulative") {
    lines <- c(lines, '
  real bivariate_cumulative_lpmf_custom(int y1, int y2, int K1, int K2,
                                         real mu1, real mu2,
                                         vector c1, vector c2, real rho) {
